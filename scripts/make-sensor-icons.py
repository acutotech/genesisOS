#!/usr/bin/env python3
"""Generate the Genesis sensor box icons (A-K) and the sensors symbolic icon.

    python3 scripts/make-sensor-icons.py

Writes SVGs into stage-custom/11-genesis-shell/files/genesis-shell/genesis_shell/icons/:
sensors/sensor-a.svg ... sensor-k.svg and genesis-sensors-symbolic.svg. They are
committed; run this again only to change the design. Standard library only.

Design: the shell's rounded-square tile with a top-lit gradient in the sensor's
hue (the same hues the original sensor tray used, darkened so a white letter
keeps at least 4.5:1 contrast), a glass sheen, and a chip outline with pins
behind the letter, so the icon reads as "sensor box A" at 24 px and at 96 px.
"""

from __future__ import annotations

import colorsys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "stage-custom" / "11-genesis-shell" / "files" / "genesis-shell" / "genesis_shell" / "icons"

# hue (degrees) per sensor box; A-I follow the original tray's colours
HUES = {
    "A": 2,     # coral red
    "B": 174,   # teal
    "C": 196,   # cyan blue
    "D": 18,    # salmon orange
    "E": 152,   # mint green
    "F": 44,    # amber
    "G": 282,   # violet
    "H": 208,   # sky blue
    "I": 30,    # apricot
    "J": 330,   # rose
    "K": 246,   # indigo
}


def hsl(h: float, s: float, light: float) -> str:
    r, g, b = colorsys.hls_to_rgb(h / 360.0, light, s)
    return "#%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))


def luminance(hex_colour: str) -> float:
    def channel(c: int) -> float:
        v = c / 255
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4

    r, g, b = (int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast_with_white(hex_colour: str) -> float:
    return 1.05 / (luminance(hex_colour) + 0.05)


def colours(hue: float) -> tuple[str, str]:
    """Top and bottom gradient stops, darkened until white text reads on the bottom stop."""
    top_l, bottom_l = 0.56, 0.42
    while contrast_with_white(hsl(hue, 0.62, (top_l + bottom_l) / 2)) < 4.5 and bottom_l > 0.2:
        top_l -= 0.02
        bottom_l -= 0.02
    return hsl(hue, 0.66, top_l), hsl(hue, 0.60, bottom_l)


def pins() -> str:
    """Three pins on each side of the chip outline (x/y 28..100)."""
    out = []
    for offset in (46, 64, 82):
        out.append(f'<rect x="{offset - 3}" y="16" width="6" height="10" rx="3"/>')   # top
        out.append(f'<rect x="{offset - 3}" y="102" width="6" height="10" rx="3"/>')  # bottom
        out.append(f'<rect x="16" y="{offset - 3}" width="10" height="6" rx="3"/>')   # left
        out.append(f'<rect x="102" y="{offset - 3}" width="10" height="6" rx="3"/>')  # right
    return "".join(out)


def sensor_svg(letter: str, hue: float) -> str:
    top, bottom = colours(hue)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">
  <!-- Genesis sensor box {letter}. Generated by scripts/make-sensor-icons.py. -->
  <defs>
    <linearGradient id="fill" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="{top}"/>
      <stop offset="1" stop-color="{bottom}"/>
    </linearGradient>
    <linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#ffffff" stop-opacity="0.30"/>
      <stop offset="0.48" stop-color="#ffffff" stop-opacity="0.04"/>
      <stop offset="0.5" stop-color="#ffffff" stop-opacity="0"/>
    </linearGradient>
  </defs>
  <rect x="4" y="4" width="120" height="120" rx="32" fill="url(#fill)"/>
  <rect x="4" y="4" width="120" height="120" rx="32" fill="url(#sheen)"/>
  <rect x="4.75" y="4.75" width="118.5" height="118.5" rx="31.25" fill="none" stroke="#ffffff" stroke-opacity="0.28" stroke-width="1.5"/>
  <g fill="#ffffff" fill-opacity="0.34">{pins()}</g>
  <rect x="28" y="28" width="72" height="72" rx="16" fill="#000000" fill-opacity="0.16" stroke="#ffffff" stroke-opacity="0.42" stroke-width="3"/>
  <text x="64" y="83.5" text-anchor="middle" font-family="Inter, 'DejaVu Sans', sans-serif" font-size="54" font-weight="700" fill="#ffffff">{letter}</text>
</svg>
"""


SYMBOLIC = """<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16">
  <!-- Genesis sensors: a chip with pins. Fills only, so GTK recolours it like any symbolic icon. -->
  <g fill="#2e3436">
    <path fill-rule="evenodd" d="M5 3h6a2 2 0 0 1 2 2v6a2 2 0 0 1 -2 2h-6a2 2 0 0 1 -2 -2v-6a2 2 0 0 1 2 -2z M5.25 4.5h5.5a0.75 0.75 0 0 1 0.75 0.75v5.5a0.75 0.75 0 0 1 -0.75 0.75h-5.5a0.75 0.75 0 0 1 -0.75 -0.75v-5.5a0.75 0.75 0 0 1 0.75 -0.75z"/>
    <rect x="6.5" y="6.5" width="3" height="3" rx="0.75"/>
    <rect x="5.25" y="0.5" width="1.5" height="2.5" rx="0.75"/>
    <rect x="9.25" y="0.5" width="1.5" height="2.5" rx="0.75"/>
    <rect x="5.25" y="13" width="1.5" height="2.5" rx="0.75"/>
    <rect x="9.25" y="13" width="1.5" height="2.5" rx="0.75"/>
    <rect x="0.5" y="5.25" width="2.5" height="1.5" rx="0.75"/>
    <rect x="0.5" y="9.25" width="2.5" height="1.5" rx="0.75"/>
    <rect x="13" y="5.25" width="2.5" height="1.5" rx="0.75"/>
    <rect x="13" y="9.25" width="2.5" height="1.5" rx="0.75"/>
  </g>
</svg>
"""


def main() -> None:
    (OUT / "sensors").mkdir(parents=True, exist_ok=True)
    for letter, hue in HUES.items():
        path = OUT / "sensors" / f"sensor-{letter.lower()}.svg"
        path.write_text(sensor_svg(letter, hue), encoding="utf-8")
        top, bottom = colours(hue)
        print(f"{path.relative_to(ROOT)}  {top} -> {bottom}  white contrast {contrast_with_white(bottom):.1f}:1")
    (OUT / "genesis-sensors-symbolic.svg").write_text(SYMBOLIC, encoding="utf-8")
    print((OUT / "genesis-sensors-symbolic.svg").relative_to(ROOT))


if __name__ == "__main__":
    main()
